// ----------------------------------------------------
// 1. Константа PI
// ----------------------------------------------------

// const объявляет константу.
//
// export позволяет импортировать её
// из другого JavaScript-модуля.
//
// В этом домашнем задании используем
// значение PI = 3.14159.

export const PI = 3.14159;


// ----------------------------------------------------
// 2. Площадь круга
// ----------------------------------------------------

// Формула площади круга:
//
// S = PI * r * r
//
// radius — радиус круга.
//
// Например:
// getCircleArea(5)
//
// Вычисление:
// 3.14159 * 5 * 5 = 78.53975

export function getCircleArea(radius) {

    // Вычисляем площадь круга.
    const area = PI * radius * radius;

    // Возвращаем вычисленное значение.
    return area;

}


// ----------------------------------------------------
// 3. Площадь прямоугольника
// ----------------------------------------------------

// Формула:
//
// S = width * height
//
// width — ширина.
// height — высота.
//
// Например:
// getRectangleArea(8, 12)
//
// Результат:
// 8 * 12 = 96

export function getRectangleArea(width, height) {

    // Вычисляем площадь.
    const area = width * height;

    // Возвращаем результат.
    return area;

}


// ----------------------------------------------------
// 4. Длина окружности
// ----------------------------------------------------

// Формула длины окружности:
//
// L = 2 * PI * r
//
// radius — радиус окружности.
//
// Например:
// getCircleLength(10)
//
// Вычисление:
// 2 * 3.14159 * 10 = 62.8318

export function getCircleLength(radius) {

    // Вычисляем длину окружности.
    const length = 2 * PI * radius;

    // Возвращаем результат.
    return length;

}