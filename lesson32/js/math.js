// ====================================================
// math.js
//
// Модуль математических операций.
//
// Здесь находятся функции для работы с числами.
//
// Каждая функция начинается со слова export.
//
// export означает:
// "Разрешаем другим JavaScript-модулям
// использовать эту функцию через import".
//
// Это именованные экспорты (Named exports).
// ====================================================


// ----------------------------------------------------
// 1. Сложение
// ----------------------------------------------------

// export делает функцию доступной другим модулям.
//
// function add(a, b) объявляет функцию,
// которая принимает два аргумента: a и b.
//
// return возвращает результат сложения
// туда, откуда была вызвана функция.

export function add(a, b) {

    return a + b;

}


// ----------------------------------------------------
// 2. Вычитание
// ----------------------------------------------------

// Функция subtract принимает два числа.
//
// Из первого числа вычитаем второе.
//
// Например:
// subtract(20, 8) вернёт 12.

export function subtract(a, b) {

    return a - b;

}


// ----------------------------------------------------
// 3. Умножение
// ----------------------------------------------------

// Функция multiply принимает два числа.
//
// Оператор * выполняет умножение.
//
// Например:
// multiply(6, 9) вернёт 54.

export function multiply(a, b) {

    return a * b;

}


// ----------------------------------------------------
// 4. Деление
// ----------------------------------------------------

// Функция divide принимает два числа.
//
// Важное условие задания:
// делить на ноль нельзя.
//
// Поэтому перед делением проверяем b.
//
// Если b === 0, возвращаем сообщение.
//
// Обратите внимание:
// мы используем return, а не console.log.
//
// Это значит, что функция отдаёт результат,
// а решение о выводе в консоль принимает app.js.

export function divide(a, b) {

    // Проверяем, равен ли делитель нулю.
    if (b === 0) {

        // Немедленно завершаем функцию
        // и возвращаем текстовое сообщение.
        return "Cannot divide by zero";

    }

    // Эта строка выполнится только тогда,
    // когда b не равен нулю.
    return a / b;

}