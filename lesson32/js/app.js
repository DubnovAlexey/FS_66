// ====================================================
// app.js
//
// Главный модуль приложения.
//
// Именно этот файл подключён в index.html.
//
// Его задача:
//
// 1. Импортировать необходимые функции.
// 2. Вызвать эти функции.
// 3. Получить результаты вычислений.
// 4. Вывести результаты в консоль.
//
// Сами математические формулы здесь не пишем.
// Они уже находятся в других модулях.
// ====================================================


// ====================================================
// ЧАСТЬ 1. ИМПОРТ МАТЕМАТИЧЕСКИХ ФУНКЦИЙ
// ====================================================

// import означает:
// "Получить что-то из другого модуля".
//
// В фигурных скобках перечисляем
// имена функций, которые хотим импортировать.
//
// from "./math.js" указывает,
// из какого файла их нужно получить.
//
// ./ означает текущую папку.
//
// app.js и math.js находятся в одной папке js,
// поэтому путь выглядит как "./math.js".
//
// Имена должны точно совпадать с экспортами.

import {
    add,
    subtract,
    multiply,
    divide
} from "./math.js";


// ====================================================
// ЧАСТЬ 2. ИМПОРТ ГЕОМЕТРИЧЕСКИХ ФУНКЦИЙ
// ====================================================

// Из geometry.js импортируем:
//
// PI — константу.
// getCircleArea — площадь круга.
// getRectangleArea — площадь прямоугольника.
// getCircleLength — длину окружности.
//
// Это тоже Named imports.
//
// Поэтому используем фигурные скобки.

import {
    PI,
    getCircleArea,
    getRectangleArea,
    getCircleLength
} from "./geometry.js";


// ====================================================
// ЧАСТЬ 3. МАТЕМАТИЧЕСКИЕ ОПЕРАЦИИ
// ====================================================

// Выводим заголовок раздела.
console.log("=== MATH OPERATIONS ===");


// ----------------------------------------------------
// Сложение: 15 + 7
// ----------------------------------------------------

// Вызываем функцию add.
//
// Передаём два аргумента: 15 и 7.
//
// Функция выполнит сложение
// и вернёт результат через return.
//
// Полученное значение сохраняем
// в переменную resultAdd.

const resultAdd = add(15, 7);

// Выводим результат в консоль.
console.log("15 + 7 =", resultAdd);


// ----------------------------------------------------
// Вычитание: 20 - 8
// ----------------------------------------------------

const resultSubtract = subtract(20, 8);

console.log("20 - 8 =", resultSubtract);


// ----------------------------------------------------
// Умножение: 6 * 9
// ----------------------------------------------------

const resultMultiply = multiply(6, 9);

console.log("6 * 9 =", resultMultiply);


// ----------------------------------------------------
// Деление: 100 / 4
// ----------------------------------------------------

const resultDivide = divide(100, 4);

console.log("100 / 4 =", resultDivide);


// ----------------------------------------------------
// Попытка деления на ноль: 10 / 0
// ----------------------------------------------------

// Вызываем функцию divide с делителем 0.
//
// Внутри divide() сработает условие:
//
// if (b === 0)
//
// Поэтому функция вернёт строку:
//
// "Cannot divide by zero"

const resultDivideZero = divide(10, 0);

console.log("10 / 0 =", resultDivideZero);


// ====================================================
// ЧАСТЬ 4. ГЕОМЕТРИЧЕСКИЕ ВЫЧИСЛЕНИЯ
// ====================================================

// Пустая строка для удобства чтения консоли.
console.log("");

console.log("=== GEOMETRY OPERATIONS ===");


// ----------------------------------------------------
// Вывод константы PI
// ----------------------------------------------------

// Константа PI объявлена в geometry.js.
//
// Но благодаря export и import
// мы можем использовать её здесь.

console.log("PI =", PI);


// ----------------------------------------------------
// Площадь круга с радиусом 5
// ----------------------------------------------------

// Вызываем getCircleArea(5).
//
// Внутри geometry.js вычисляется:
//
// PI * 5 * 5
//
// Результат возвращается в app.js.

const circleArea = getCircleArea(5);

console.log("Circle area (r=5):", circleArea);


// ----------------------------------------------------
// Площадь прямоугольника 8 x 12
// ----------------------------------------------------

// Функция принимает два аргумента:
//
// width = 8
// height = 12
//
// Результат: 96

const rectangleArea = getRectangleArea(8, 12);

console.log(
    "Rectangle area (8x12):",
    rectangleArea
);


// ----------------------------------------------------
// Длина окружности с радиусом 10
// ----------------------------------------------------

// Функция использует формулу:
//
// 2 * PI * radius
//
// При radius = 10 результат 62.8318.

const circleLength = getCircleLength(10);

console.log(
    "Circle length (r=10):",
    circleLength
);


// ====================================================
// КОНЕЦ ПРОГРАММЫ
// ====================================================

// Все вычисления выполнены.
//
// app.js не содержит реализаций функций.
//
// Он только импортирует и использует их.
//
// Это и есть основная идея модульного подхода.

console.log("");
console.log("Application finished");