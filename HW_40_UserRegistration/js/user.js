// ===== user.js — создание пользователя и проверка корректности его данных =====

// --- Генератор уникальных идентификаторов (счётчик на замыкании) ---

function createIdGenerator() { // Фабрика: при вызове создаёт новый независимый счётчик
    let lastId = 0; // Приватная переменная-счётчик: она живёт внутри фабрики, снаружи к ней не добраться
    return function nextId() { // Возвращаем внутреннюю функцию; она «запоминает» lastId — это и есть замыкание
        lastId += 1; // Увеличиваем счётчик на единицу при каждом вызове
        return lastId; // Отдаём новый номер: он ещё ни разу не выдавался
    }; // Конец внутренней функции nextId
} // Конец фабрики createIdGenerator

const nextUserId = createIdGenerator(); // Создаём один общий генератор на всё приложение: повторов id не будет

// --- Допустимые границы возраста ---

const MIN_AGE = 0; // Минимально допустимый возраст (включительно)
const MAX_AGE = 120; // Максимально допустимый возраст (включительно)

// --- Создание пользователя ---

function createUser({ name, age, ...extraProps }) { // Один аргумент-объект; деструктуризация достаёт name и age, а Rest (...) собирает остальные свойства в extraProps
    console.log('[createUser] Checking data for a new user...'); // Сообщение в консоль: начинаем проверку

    if (typeof name !== 'string' || name.trim() === '') { // Имя не передано (не строка) либо пустое / состоит только из пробелов
        throw new Error('Name is required'); // Создаём ошибку с текстом из задания и «бросаем» её — выполнение функции прерывается
    } // Конец проверки имени

    const cleanName = name.trim(); // Убираем пробелы в начале и в конце имени

    const isAgeMissing = age === undefined || age === null || String(age).trim() === ''; // Возраст «не введён»: значения нет или пустая строка (её проверяем отдельно, ведь Number('') даёт 0)
    if (isAgeMissing) { // Если возраст не введён
        throw new Error('Age is required'); // Бросаем ошибку «возраст обязателен»
    } // Конец проверки наличия возраста

    const numericAge = Number(age); // Приводим возраст к числу (если это уже число — оно не изменится)
    const isAgeValid = Number.isInteger(numericAge) && numericAge >= MIN_AGE && numericAge <= MAX_AGE; // Возраст допустим, если он целый и лежит в диапазоне от 0 до 120
    if (!isAgeValid) { // Если возраст не прошёл проверку (NaN, дробный, отрицательный, больше 120)
        throw new Error('Invalid age'); // Бросаем ошибку «некорректный возраст»
    } // Конец проверки значения возраста

    const user = { ...extraProps, id: nextUserId(), name: cleanName, age: numericAge }; // Spread (...) копирует дополнительные свойства; id, name и age записаны после них, чтобы их нельзя было подменить извне
    console.log(`[createUser] User created: id=${user.id}, name="${user.name}", age=${user.age}`); // Сообщение в консоль: пользователь создан
    return user; // Возвращаем готовый объект пользователя
} // Конец функции createUser