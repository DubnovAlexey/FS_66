// Создаём менеджер с внутренним массивом, доступным только через предусмотренные методы. // Это демонстрация замыкания и инкапсуляции.
function createUserManager() { // Объявляем фабрику закрытого хранилища пользователей.
    let users = []; // Создаём локальный массив; при удалении он будет заменяться новым, поэтому используем let.

    return { // Отдаём наружу объект с методами, сохраняя users внутри замыкания.
        addUser(user) { // Принимаем готовый объект, созданный и проверенный функцией createUser.
            users.push(user); // Добавляем пользователя в конец внутреннего массива методом push.
        }, // Завершаем операцию добавления.

        getUsers() { // Даём вызывающему коду способ получить список без доступа к оригинальному массиву.
            return [...users]; // Spread создаёт новый массив с теми же записями, не выдавая ссылку на users.
        }, // Завершаем операцию чтения списка.

        removeUser(userId) { // Принимаем id записи, которую необходимо удалить.
            const originalLength = users.length; // Сохраняем длину до фильтрации, чтобы определить результат.
            users = users.filter(({ id }) => id !== userId); // filter создаёт массив без совпавшего id, а деструктуризация достаёт id каждой записи.
            return users.length < originalLength; // Возвращаем true, если массив действительно стал короче.
        }, // Завершаем удаление по идентификатору.
    }; // Возвращаем только разрешённый интерфейс для работы с коллекцией.
} // Завершаем фабрику менеджера.