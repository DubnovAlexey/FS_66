// Создаём отдельный счётчик, выдающий уникальные номера в рамках текущего запуска страницы. // Комментарий заранее объясняет назначение фабрики.
function createIdGenerator() { // Объявляем фабрику функции для выдачи идентификаторов.
    let lastId = 0; // Храним последний номер; let нужен, потому что это значение будет увеличиваться.
    return function nextId() { // Возвращаем внутреннюю функцию, которая продолжит видеть переменную lastId.
        lastId += 1; // Увеличиваем запомненный номер на единицу.
        return lastId; // Возвращаем следующий номер вызывающему коду.
    }; // Завершаем внутреннюю функцию и передаём её наружу.
} // Завершаем фабрику генератора.

// Создаём один генератор для всех пользователей этого приложения. // Однократный вызов сохраняет общий счётчик.
const nextUserId = createIdGenerator(); // Сохраняем функцию, которая при каждом вызове выдаёт новое число.

// Проверяем входные данные и создаём новый объект пользователя. // Функция не зависит от страницы и может проверяться отдельно.
function createUser({ name, age, ...extraProps } = {}) { // Принимаем один объект, деструктурируем имя и возраст, собираем остаток в extraProps.
    if (typeof name !== "string" || name.trim() === "") { // Отсекаем отсутствующее имя и текст, состоящий только из пробелов.
        throw new Error("Name is required"); // Создаём исключение с заданным сообщением и останавливаем функцию.
    } // Завершаем проверку имени.

    const cleanName = name.trim(); // Удаляем пробелы с обоих краёв имени и сохраняем очищенный вариант.

    if (age === null || age === undefined || (typeof age === "string" && age.trim() === "")) { // Проверяем отсутствие возраста до его числового преобразования.
        throw new Error("Age is required"); // Не позволяем Number превратить пустую строку в допустимый ноль.
    } // Завершаем проверку пустого возраста.

    if (typeof age !== "number" && typeof age !== "string") { // Принимаем только число или его текстовую запись.
        throw new Error("Invalid age"); // Отклоняем значения вроде true, которые Number преобразовал бы в 1.
    } // Завершаем проверку типа возраста.

    const numericAge = Number(age); // Преобразуем строку с цифрами в тип number встроенной функцией Number.

    if (!Number.isInteger(numericAge) || numericAge < 0 || numericAge > 120) { // Проверяем целое число и границы от 0 до 120 включительно.
        throw new Error("Invalid age"); // Останавливаем создание записи при дробном, нечисловом или недопустимом возрасте.
    } // Завершаем проверку допустимого диапазона.

    return { // Создаём и сразу возвращаем новый объект пользователя.
        ...extraProps, // Spread переносит дополнительные исходные свойства в новый объект.
        id: nextUserId(), // Генерируем служебный id после spread, защищая его от переданного extraProps.id.
        name: cleanName, // Сохраняем очищенное имя.
        age: numericAge, // Сохраняем возраст именно числом.
    }; // Завершаем новый объект и возвращаем его вызывающему коду.
} // Завершаем создание пользователя.
